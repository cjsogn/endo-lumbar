    fpath = os.path.join(models, fname)
    if os.path.exists(fpath):
        idata = az.from_netcdf(fpath)
        # Get beta_treatment from posterior
        if 'posterior' in idata.groups():
            post = idata.posterior
            # Find treatment variable
            treatment_var = None
            for var in post.data_vars:
                if 'treatment' in var.lower() or var == 'beta_treatment':
                    treatment_var = var
                    break
            if treatment_var is None:
                # Try beta[0] or similar
                for var in post.data_vars:
                    if 'beta' in var.lower():
                        treatment_var = var
                        break
            if treatment_var is not None:
                vals = post[treatment_var].values
                if vals.ndim == 2:
                    # (chain, draw) - plot each chain
                    for c in range(min(4, vals.shape[0])):
                        ax_trace.plot(vals[c, :], alpha=0.35, linewidth=0.3,
                                      color=trace_colors[idx])

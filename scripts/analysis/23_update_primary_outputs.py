# Shorten labels
def shorten_label(s):
    s = s.replace(' months', 'm')
    s = s.replace(' pain', '')
    s = s.replace('success ', '')
    s = s.replace(' (>=30% or >=10pt)', '')
    s = s.replace('Return to work', 'RTW')
    s = s.replace('Analgesic use', 'Analgesic')
    s = s.replace('GPE success', 'GPE')
    return s

def draw_comparison_panel(ax, df, panel_label, fmt_str=".2f"):
    df = df.iloc[::-1].reset_index(drop=True)  # Reverse for bottom-up
    n = len(df)
    offset = 0.12

    # Find x range for annotation positioning
    all_hi = max(df['brms_CrI_hi'].max(), df['PyMC_CrI_hi'].max())
    all_lo = min(df['brms_CrI_lo'].min(), df['PyMC_CrI_lo'].min())
    x_range = all_hi - all_lo
    annot_x = all_hi + x_range * 0.06

    for i, row in df.iterrows():
        # brms (blue circles, offset down)
        ax.errorbar(row['brms_ATE'], i - offset,
                    xerr=[[row['brms_ATE'] - row['brms_CrI_lo']],
                          [row['brms_CrI_hi'] - row['brms_ATE']]],
                    fmt='o', color=COL_ELD, markersize=5,
                    elinewidth=0.7, capsize=2, capthick=0.7, zorder=4)

        # PyMC (orange squares, offset up)
        ax.errorbar(row['PyMC_ATE'], i + offset,
                    xerr=[[row['PyMC_ATE'] - row['PyMC_CrI_lo']],
                          [row['PyMC_CrI_hi'] - row['PyMC_ATE']]],
                    fmt='s', color=COL_ORANGE, markersize=5,
                    elinewidth=0.7, capsize=2, capthick=0.7, zorder=4)

        # N_gcomp annotation (only show if different)
        brms_n = int(row['brms_N_gcomp'])
        pymc_n = int(row['PyMC_N_gcomp'])
        if brms_n != pymc_n:
            n_text = f"N: {brms_n}/{pymc_n}"
        else:
            n_text = f"N={brms_n}"

        # Right-side text annotation in data coordinates
        ax.text(annot_x, i, n_text, fontsize=7, color='0.40',
                va='center', ha='left', zorder=10)

    ax.axvline(0, linestyle='-', color='0.50', linewidth=0.4, zorder=1)

    labels = [shorten_label(row['Outcome']) for _, row in df.iterrows()]
    ax.set_yticks(range(n))
    ax.set_yticklabels(labels, fontsize=9)
    ax.set_ylim(-0.6, n - 0.4)

    ax.set_title(panel_label, fontsize=10.5, fontweight='bold', loc='left')
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)

    # Expand x axis for annotations
    ax.set_xlim(all_lo - x_range * 0.05, annot_x + x_range * 0.35)

    # Legend
    handles = [
        Line2D([0], [0], marker='o', color=COL_ELD, linestyle='-',
               markersize=6, linewidth=0.7, label='brms'),
        Line2D([0], [0], marker='s', color=COL_ORANGE, linestyle='-',
               markersize=6, linewidth=0.7, label='PyMC'),
    ]
    ax.legend(handles=handles, fontsize=9, loc='lower right', framealpha=0.9)

# Panel A: Continuous
